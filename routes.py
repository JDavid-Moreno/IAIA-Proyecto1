def build_routes_by_station(routes: dict) -> dict:
    routes_by_station: dict[str, list[str]] = {}

    for route_id, data in routes.items():
        for station in data["stations"]:
            routes_by_station.setdefault(station, [])

            if route_id not in routes_by_station[station]:
                routes_by_station[station].append(route_id)

    return routes_by_station


